#!/bin/sh
# Makes one product's two firmware signing keys, once, on Dan's Mac, and writes their public halves
# into the firmware's key header (committed: a public key is meant to be public). One script for
# every product (DEVICES.md §3); each product keeps its own keys, so one can never sign another's.
#
#   make_signing_keys.sh --product pala   --header-out src/app/ota_keys.h [--header-only]
#   make_signing_keys.sh --product reread --header-out lib/OtaSignature/OtaKeys.h [--header-only]
#
# <product>-a signs today; <product>-b is the next key. Every build carries both, so a later build
# can switch to -b and still be accepted, and -a can then be retired. The private keys live in
# ~/.config/<product>-signing (or $<PRODUCT>_SIGNING_DIR; folder 700, files 600): never in a repo,
# never on the Pi. Back the folder up offline: losing it means a USB flash for every device.
# Product wrappers: Pala tools/make_signing_keys.sh, reRead tools/ota-signing/make_signing_keys.sh.
set -eu
PRODUCT=""; HEADER=""; ONLY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --product) PRODUCT="$2"; shift 2 ;;
    --header-out) HEADER="$2"; shift 2 ;;
    --header-only|--header) ONLY=1; shift ;;
    *) echo "usage: $0 --product NAME --header-out FILE [--header-only]" >&2; exit 2 ;;
  esac
done
case "$PRODUCT" in
  ""|*[!a-z0-9]*) echo "--product must be lower-case letters and digits" >&2; exit 2 ;;
esac
[ -n "$HEADER" ] || { echo "--header-out is required" >&2; exit 2; }
UPPER=$(printf '%s' "$PRODUCT" | tr '[:lower:]' '[:upper:]')
DIR=$(eval "printf '%s' \"\${${UPPER}_SIGNING_DIR:-}\"")
[ -n "$DIR" ] || DIR="$HOME/.config/$PRODUCT-signing"
HEADER_DIR=$(cd "$(dirname "$HEADER")" && pwd -P)
REPO=$(cd "$HEADER_DIR" && git rev-parse --show-toplevel 2>/dev/null || echo "$HEADER_DIR")
REAL_DIR="$(cd "$(dirname "$DIR")" 2>/dev/null && pwd -P || dirname "$DIR")/$(basename "$DIR")"
case "$REAL_DIR" in
  "$REPO"/*) echo "refusing: $DIR is inside the repo" >&2; exit 1 ;;
esac

A="$PRODUCT-a"; B="$PRODUCT-b"
if [ "$ONLY" -eq 0 ]; then
  umask 077
  mkdir -p "$DIR"
  chmod 700 "$DIR"
  for id in "$A" "$B"; do
    if [ -e "$DIR/$id.pem" ]; then
      echo "$id: already there, leaving it alone"
      continue
    fi
    openssl ecparam -name prime256v1 -genkey -noout -out "$DIR/$id.pem" 2>/dev/null
    chmod 600 "$DIR/$id.pem"
    echo "$id: made $DIR/$id.pem"
  done
fi

for id in "$A" "$B"; do
  [ -r "$DIR/$id.pem" ] || { echo "no $DIR/$id.pem" >&2; exit 1; }
  openssl ec -in "$DIR/$id.pem" -pubout -out "$DIR/$id.pub.pem" 2>/dev/null
  chmod 644 "$DIR/$id.pub.pem"
done

pem_lines() { sed 's/^/  "/; s/$/\\n"/' "$1"; }
{
  echo "#pragma once"
  echo "// $PRODUCT firmware signing public keys. Generated by app-kit's make_signing_keys.sh; the private"
  echo "// halves are on Dan's Mac only (~/.config/$PRODUCT-signing). Every build carries both: $A signs"
  echo "// now, $B is next, so the key can be rotated with one ordinary update."
  echo "#define OTA_KEY_ID_CURRENT \"$A\""
  echo "#define OTA_KEY_ID_NEXT    \"$B\""
  echo "#define OTA_PUBLIC_KEY_CURRENT \\"
  pem_lines "$DIR/$A.pub.pem" | sed 's/$/ \\/'
  echo "  \"\""
  echo "#define OTA_PUBLIC_KEY_NEXT \\"
  pem_lines "$DIR/$B.pub.pem" | sed 's/$/ \\/'
  echo "  \"\""
} > "$HEADER"
echo "wrote $HEADER"
